import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {

  return new Promise((resolve, reject) => {

    const doc = new PDFDocument({
      size: "A4",
      margin: 50,

      info: {
        Author: "CortexAI",
        Title: data.title || "CortexAI Document",
        Creator: "CortexAI",
      },
    });

    const chunks = [];


    // -----------------------------------------
    // DATA
    // -----------------------------------------

    doc.on("data", (chunk) => {
      chunks.push(chunk);
    });


    // -----------------------------------------
    // PDF COMPLETE
    // -----------------------------------------

    doc.on("end", () => {
      resolve(Buffer.concat(chunks));
    });


    // -----------------------------------------
    // PDF ERROR
    // -----------------------------------------

    doc.on("error", (error) => {
      reject(error);
    });


    // -----------------------------------------
    // TITLE
    // -----------------------------------------

    doc
      .fontSize(28)
      .fillColor("#111827")
      .text(
        data.title || "CortexAI Document",
        {
          align: "center",
        }
      );


    // -----------------------------------------
    // SUBTITLE
    // -----------------------------------------

    if (data.subtitle) {

      doc.moveDown(0.5);

      doc
        .fontSize(12)
        .fillColor("#6B7280")
        .text(
          data.subtitle,
          {
            align: "center",
          }
        );
    }


    doc.moveDown(2);


    // -----------------------------------------
    // SECTIONS
    // -----------------------------------------

    data?.sections?.forEach((section) => {

      doc
        .fontSize(18)
        .fillColor("#111827")
        .text(
          section.heading || ""
        );


      doc.moveDown(0.5);


      section?.points?.forEach((point) => {

        doc
          .fontSize(12)
          .fillColor("#6B7280")
          .text(
            "• " + point,
            {
              lineGap: 5,
            }
          );

      });


      doc.moveDown();

    });


    // -----------------------------------------
    // FOOTER
    // -----------------------------------------

    doc.moveDown();

    doc
      .fontSize(10)
      .fillColor("#9CA3AF")
      .text(
        "Generated By CortexAI",
        {
          align: "center",
        }
      );


    // -----------------------------------------
    // END PDF
    // -----------------------------------------

    doc.end();

  });

};



