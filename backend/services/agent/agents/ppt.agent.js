import { getModel } from "../config/llmModel.js";

import { generatePpt } from "../utils/generatePpt.js";
import { uploadToS3 } from "../utils/uploadToS3.js";
import { newFileName, userFileKey, fileUrl } from "../utils/userFile.js";
import { checkAgentLimit } from "../config/agentLimit.js";

export const pptAgent = async (state) => {
    try {
        await checkAgentLimit(state.userId, "ppt")
        console.log(
            "📊 PPT AGENT STATE:",
            state
        );

        // -----------------------------------------
        // GET PPT MODEL
        // -----------------------------------------

        const llm = await getModel("ppt");

        // -----------------------------------------
        // PROMPT
        // -----------------------------------------

        const prompt = `
You are a professional presentation designer.

Return ONLY valid JSON.

Use exactly this format:

{
    "title": "",
    "subtitle": "",
    "slides": [
        {
            "title": "",
            "points": [
                "",
                "",
                "",
                ""
            ]
        }
    ]
}

Rules:

- Generate exactly 6 content slides.
- Each slide should have 4-6 concise bullet points.
- No markdown.
- No explanation.
- No code block.
- Return ONLY valid JSON.
- Do not add any text before or after the JSON.

Topic:
${state.prompt}
`;

        // -----------------------------------------
        // CALL LLM
        // -----------------------------------------

        const res = await llm.invoke(prompt);

        console.log(
            "🤖 PPT LLM RESPONSE:",
            res.content
        );

        // -----------------------------------------
        // PARSE JSON
        // -----------------------------------------

        let data;

        try {
            let content = String(
                res.content
            ).trim();

            content = content
                .replace(/^```json\s*/i, "")
                .replace(/^```\s*/i, "")
                .replace(/\s*```$/i, "")
                .trim();

            data = JSON.parse(content);

        } catch (error) {
            console.error(
                "❌ PPT JSON PARSE ERROR:",
                error
            );

            console.error(
                "❌ RAW PPT RESPONSE:",
                res.content
            );

            throw new Error(
                "PPT agent returned invalid JSON"
            );
        }

        // -----------------------------------------
        // VALIDATE PPT DATA
        // -----------------------------------------

        if (
            !data ||
            typeof data !== "object"
        ) {
            throw new Error(
                "Invalid PPT data"
            );
        }

        if (!data.title) {
            data.title =
                "CortexAI Presentation";
        }

        if (!data.subtitle) {
            data.subtitle =
                "Generated by CortexAI";
        }

        if (!Array.isArray(data.slides)) {
            data.slides = [];
        }

        console.log(
            "📊 PPT DATA:",
            data
        );

        // -----------------------------------------
        // GENERATE PPT
        // -----------------------------------------

        const buffer =
            await generatePpt(data);

        console.log(
            "✅ PPT BUFFER GENERATED"
        );

        // -----------------------------------------
        // CREATE FILE NAME
        // -----------------------------------------

        const filename = newFileName("ppt", "pptx");

        console.log(
            "📁 PPT FILENAME:",
            filename
        );

        // -----------------------------------------
        // UPLOAD TO S3
        // -----------------------------------------

        await uploadToS3(
            userFileKey(state.userId, filename),
            buffer,
            "application/vnd.openxmlformats-officedocument.presentationml.presentation"
        );

        console.log(
            "☁️ PPT UPLOADED TO S3"
        );

        // -----------------------------------------
        // SIGNED DOWNLOAD URL
        // -----------------------------------------

        const downloadUrl = fileUrl(state.userId, filename);

        console.log(
            "🔗 PPT DOWNLOAD URL GENERATED"
        );

        // -----------------------------------------
        // DEDUCT CREDIT
        // -----------------------------------------


        // -----------------------------------------
        // RETURN STATE
        // -----------------------------------------

        return {
            ...state,

            aiResponse: `# Presentation Generated

**${data.title}**

${data.subtitle || ""}

[📥 Download PPT](${downloadUrl})
`,

            artifacts: [
                {
                    type: "ppt",
                    title: data.title,
                    subtitle:
                        data.subtitle || "",
                    slides: data.slides,
                    downloadUrl,
                },
            ],
        };

    } catch (error) {
        // rate-limit (429) and credit errors go back to the client as-is
        if (error.status) throw error;

        console.error(
            "❌ PPT AGENT ERROR:",
            error
        );

        console.error(
            "❌ PPT ERROR MESSAGE:",
            error.message
        );

        console.error(
            "❌ PPT ERROR STACK:",
            error.stack
        );

        return {
            ...state,
            failed: true,

            aiResponse:
                `Failed to generate PPT. ${error.message}`,

            artifacts: [],
        };
    }
};