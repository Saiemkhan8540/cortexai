import { getModel } from "../config/llmModel.js";

import { generatePdf } from "../utils/generatePdf.js";
import { uploadToS3 } from "../utils/uploadToS3.js";
import { newFileName, userFileKey, fileUrl } from "../utils/userFile.js";
import { checkAgentLimit } from "../config/agentLimit.js";

export const pdfAgent = async (state) => {
    try {
      await checkAgentLimit(state.userId, "pdf")
        console.log(
            "📄 PDF AGENT STATE:",
            state
        );

        // -----------------------------------------
        // GET PDF MODEL
        // -----------------------------------------

        const llm = await getModel("pdf");

        // -----------------------------------------
        // PROMPT
        // -----------------------------------------

        const prompt = `
You are an expert document writer.

Return ONLY valid JSON.

Do NOT return markdown.

Do NOT return explanations.

Use exactly this structure:

{
    "title": "",
    "subtitle": "",
    "sections": [
        {
            "heading": "",
            "points": []
        }
    ]
}

Generate 4-8 sections.

Each section should have 3-6 concise bullet points.

Topic:

${state.prompt}
`;

        // -----------------------------------------
        // CALL LLM
        // -----------------------------------------

        const res = await llm.invoke(
            prompt
        );

        console.log(
            "🤖 PDF LLM RESPONSE:",
            res.content
        );

        // -----------------------------------------
        // PARSE JSON
        // -----------------------------------------

        let data;

        try {
            let content = String(
                res.content
            ).trim();

            content = content
                .replace(/^```json\s*/i, "")
                .replace(/^```\s*/i, "")
                .replace(/\s*```$/i, "")
                .trim();

            data = JSON.parse(content);

        } catch (error) {
            console.error(
                "❌ PDF JSON PARSE ERROR:",
                error
            );

            console.error(
                "❌ RAW PDF RESPONSE:",
                res.content
            );

            throw new Error(
                "PDF agent returned invalid JSON"
            );
        }

        // -----------------------------------------
        // VALIDATE DATA
        // -----------------------------------------

        if (
            !data ||
            typeof data !== "object"
        ) {
            throw new Error(
                "Invalid PDF data"
            );
        }

        if (!data.title) {
            data.title =
                "CortexAI Document";
        }

        if (!data.subtitle) {
            data.subtitle =
                "Generated by CortexAI";
        }

        if (!Array.isArray(data.sections)) {
            data.sections = [];
        }

        console.log(
            "📄 PDF DATA:",
            data
        );

        // -----------------------------------------
        // GENERATE PDF
        // -----------------------------------------

        const pdfBuffer =
            await generatePdf(data);

        console.log(
            "✅ PDF generated successfully"
        );

        // -----------------------------------------
        // FILE NAME
        // -----------------------------------------

        const filename = newFileName("pdf", "pdf");

        console.log(
            "📁 PDF FILENAME:",
            filename
        );

        // -----------------------------------------
        // UPLOAD TO S3
        // -----------------------------------------

        await uploadToS3(
            userFileKey(state.userId, filename),
            pdfBuffer,
            "application/pdf"
        );

        console.log(
            "☁️ PDF uploaded to S3:",
            filename
        );

        // -----------------------------------------
        // SIGNED DOWNLOAD URL
        // -----------------------------------------

        const downloadUrl = fileUrl(state.userId, filename);

        console.log(
            "🔗 PDF DOWNLOAD URL GENERATED"
        );

        // -----------------------------------------
        // DEDUCT CREDIT
        // -----------------------------------------


        // -----------------------------------------
        // RETURN
        // -----------------------------------------

        return {
            ...state,

            aiResponse: `# PDF Generated

**${data.title}**

${data.subtitle || ""}

[📥 Download PDF](${downloadUrl})
`,

            artifacts: [
                {
                    type: "pdf",
                    title: data.title,
                    subtitle:
                        data.subtitle || "",
                    sections:
                        data.sections,
                    downloadUrl,
                },
            ],
        };

    } catch (error) {
        // rate-limit (429) and credit errors go back to the client as-is
        if (error.status) throw error;

        console.error(
            "❌ PDF AGENT ERROR:",
            error
        );

        console.error(
            "❌ PDF ERROR MESSAGE:",
            error.message
        );

        console.error(
            "❌ PDF ERROR STACK:",
            error.stack
        );

        return {
            ...state,
            failed: true,

            aiResponse:
                `Failed to generate PDF. ${error.message}`,

            artifacts: [],
        };
    }
};